  check(await page.locator('#multi-chart rect').count()===100,'Multiparameter Hilbert grid computed');
  await page.locator('[data-lab="image"]').click();await page.locator('#run-image').click();
  await page.waitForFunction(()=>document.querySelector('#image-euler svg'));
