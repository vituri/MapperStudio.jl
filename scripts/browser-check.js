  await page.locator('#data-search').fill('');await save(page.locator('#export-data'),'data.csv');
  const workspace=await save(page.locator('#workspace-save'),'workspace.json');
  await page.locator('#workspace-file').setInputFiles(workspace);
  await page.waitForFunction(()=>document.getElementById('status').textContent.includes('Workspace opened'));
