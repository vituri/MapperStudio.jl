  await page.locator('[data-tab="data"]').click();
  check(await page.locator('#data-table img').count()===0,'Categorical HTML displayed safely');
  // Failed requests preserve the existing usable model and give a concrete error.
  const before=await page.evaluate(()=>studio.model.id);
  for(const checkbox of await page.locator('#columns input').all())await checkbox.uncheck();
