  await page.locator('[data-tab="mapper"]').click();
  await save(page.locator('#export-svg'),'mapper.svg');await save(page.locator('#export-graph'),'mapper.json');
  await page.locator('#pipeline details').last().evaluate(e=>e.open=true);
  await save(page.locator('#export-script'),'analysis.jl');
